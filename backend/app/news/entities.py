def extract_regions(text: str) -> list[str]:
    low = re.sub(r"московск\w* бирж\w*|мосбирж\w*", " ", text.lower())
    out: list[str] = []
    for rx, name in _REGION_RES:
        if rx.search(low) and name not in out:
            out.append(name)
    return out[:5]


def extract_industries(text: str) -> list[str]:
    low = text.lower()
    out: list[str] = []
    for rx, code in _INDUSTRY_RES:
        if rx.search(low) and code not in out:
            out.append(code)
    return out[:5]


def extract_effective_dates(text: str, published_at: str | None = None) -> list[str]:
    """Даты вступления в силу/начала действия в формате ISO. Год без указания — ближайший после публикации."""
    try:
        base = datetime.fromisoformat((published_at or "").replace("Z", "+00:00")).date() if published_at else date.today()
    except ValueError:
        base = date.today()
    out: list[str] = []

    def add(d: date) -> None:
        iso = d.isoformat()
        if iso not in out and d >= base.replace(day=1):
            out.append(iso)

    for m in _DATE_RE.finditer(text):
        day, mon_stem, year = int(m.group(1)), m.group(2).lower(), m.group(3)
        mon = MONTHS.get(mon_stem[:6]) or next((v for k, v in MONTHS.items() if mon_stem.startswith(k)), None)
        if not mon:
            continue
        y = int(year) if year else base.year
        try:
            d = date(y, mon, day)
        except ValueError:
            continue
        if not year and d < base:
            d = date(y + 1, mon, day)
        add(d)
    for m in _DATE_NUM_RE.finditer(text):
        try:
            add(date(int(m.group(3)), int(m.group(2)), int(m.group(1))))
        except ValueError:
            continue
    for m in _YEAR_RE.finditer(text):
        y = int(m.group(1))
        if base.year <= y <= base.year + 5:
            add(date(y, 1, 1))
    return sorted(out)[:3]


def is_noise(title: str, text: str = "") -> bool:
    """Новость вне бизнес-повестки (спорт, шоу-бизнес и т.п.) — не тратим на неё LLM и не показываем."""
    return bool(NOISE_RE.search(title)) or (bool(NOISE_RE.search(text[:300])) and len(title) < 40)
